import { parseGame, type Scalar } from '../src/types/game'
import { game } from './game-fixture'
export function cooperativeSnapshot(
  story: string,
  role: 'a' | 'b',
  version: number,
  stage: string,
  visual: Record<string, Scalar> = {},
  ending: string | null = null,
) {
  const base = game()
  return parseGame({
    ...base,
    script_id: story,
    role,
    version,
    scene_id: stage,
    completed: stage === 'completed',
    public: {
      ...base.public,
      ending,
      recap: { ...base.public.recap, summary: ending ? `TEST-ONLY 服务端结局 ${ending}` : null },
    },
    available_actions: stage === 'completed' ? [] : base.available_actions,
    presentation: {
      background: null,
      cues: [],
      visual_state: Object.entries(visual).map(([id, value]) => ({ id, value })),
    },
  })
}
